/**
 * Operações são todas as ações que podem ser realizadas em um programa.
 * 
 * Para ter uma operação devemos ter:
 * - Operadores: Vão representar a ação a ser realizada
 * - Operandos: Vão representar os dados que serão manipulados
 * 
 * Basicamente, um programa de computador só existe com dados e operações.
 */

int a = 10; // Operando (Dado 1)
int b = 20; // Operando (Dado 2)

int soma = a + b; // Operação de adição (Operador: +, Operandos: a e b)
int subtracao = a - b; // Operação de subtração (Operador: -, Operandos: a e b)


