/**
 * Operações de Atribuição são usadas para mudar o valor de uma variável
 */

/**
 * Operação de atribuição simples (=)
 * Possui um lvalue e rvalue
 */
int a = 10; // A variável 'a' recebe o valor 10
int a = a + 1; // 'a' será 11

/**
 * Operadores de atribuição composta (+=, -=, *=, /=, %=)
 * Permitem realizar uma operação e atribuir o resultado à variável em uma
 * única expressão
 */
a += 5; // 'a' agora é 16 (equivalente a a = a + 5)
a -= 3; // 'a' agora é 13
a *= 2; // 'a' agora é 26
a /= 2; // 'a' agora é 13
a %= 5; // 'a' agora é 3

